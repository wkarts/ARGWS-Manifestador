#!/usr/bin/env python3
"""Explicit, pinned ACBr schema update for maintainers. Never invoked at runtime."""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
import xml.etree.ElementTree as ET

URL = 'https://svn.code.sf.net/p/acbr/code/trunk2/Exemplos/ACBrDFe/Schemas'
ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'src-tauri/resources/fiscal/schemas'
MODALS = ['cteModal'+name+'_v4.00.xsd' for name in ['Rodoviario','Aereo','Aquaviario','Ferroviario','Dutoviario']] + ['cteMultiModal_v4.00.xsd']
ROOTS = {'nfe': ['nfe_v4.00.xsd','procNFe_v4.00.xsd','distDFeInt_v1.01.xsd'], 'cte': ['cte_v4.00.xsd','procCTe_v4.00.xsd'] + MODALS}

def collect(source, names):
    files = {}
    def visit(name):
        if not re.fullmatch(r'[A-Za-z0-9_.-]+\.xsd', name):
            raise ValueError('Non-local or unsafe schema reference: '+name)
        if name in files: return
        p=source/name
        if p.is_symlink() or not p.is_file() or p.stat().st_size>10*1024*1024: raise ValueError('Invalid schema file: '+name)
        data=p.read_bytes()
        if b'<!DOCTYPE' in data.upper() or b'<!ENTITY' in data.upper(): raise ValueError('DTD not allowed in schema: '+name)
        doc=ET.fromstring(data)
        if doc.tag!='{http://www.w3.org/2001/XMLSchema}schema': raise ValueError('Not an XSD: '+name)
        files[name]=data
        for node in doc.iter():
            if node.tag in ('{http://www.w3.org/2001/XMLSchema}include','{http://www.w3.org/2001/XMLSchema}import'):
                location=node.get('schemaLocation')
                if location: visit(location)
    for name in names: visit(name)
    return files

def wrapper():
    return ('<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" targetNamespace="http://www.portalfiscal.inf.br/cte" elementFormDefault="qualified">'+''.join('<xs:include schemaLocation="'+n+'"/>' for n in ROOTS['cte'])+'</xs:schema>').encode()

def index():
    lines=['// Generated by scripts/fiscal/update-schemas.py; schemas remain offline.','const SCHEMAS: &[(&str, &[u8])] = &[']
    for group in ROOTS:
        for path in sorted((DEST/group).glob('*.xsd')):
            name=path.name if group=='nfe' else group+'/'+path.name
            lines.append(f'    ("{name}", include_bytes!("../resources/fiscal/schemas/{group}/{path.name}")),')
    lines.append('];')
    (ROOT/'src-tauri/src/fiscal_schema_files.rs').write_text('\n'.join(lines)+'\n')

def verify():
    for group in ROOTS:
        path=DEST/group
        meta=json.loads((path/'manifest.json').read_text())
        actual={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in path.glob('*.xsd')}
        if actual!=meta['files']: raise ValueError('Hash inventory differs: '+group)
        collect(path,ROOTS[group])
    print('Schema hashes and local dependency graphs verified (NF-e/NFC-e and CT-e).')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--revision',type=int,help='Explicit upstream SVN revision; downloads only at this revision')
    parser.add_argument('--verify',action='store_true',help='Offline inventory verification only')
    args=parser.parse_args()
    if args.verify: verify(); return
    if not args.revision or args.revision<1: parser.error('--revision is required; implicit latest updates are forbidden')
    with tempfile.TemporaryDirectory(prefix='acbr-schemas-') as tmp:
        base=Path(tmp); staged=base/'staged';staged.mkdir()
        # Explicit developer operation, never part of application startup or ordinary build.
        subprocess.run(['svn','export','--non-interactive','-r',str(args.revision),URL,str(base/'upstream')],check=True)
        for group,roots in ROOTS.items():
            source=base/'upstream'/({'nfe':'NFe','cte':'CTe'}[group])
            files=collect(source,roots)
            if group=='cte': files['cte-package_v4.00.xsd']=wrapper()
            out=staged/group;out.mkdir()
            for name,data in files.items(): (out/name).write_bytes(data)
            meta={'source_url':URL,'svn_revision':args.revision,'generated_files':['cte-package_v4.00.xsd'] if group=='cte' else [],'files':{n:hashlib.sha256(d).hexdigest() for n,d in sorted(files.items())}}
            (out/'manifest.json').write_text(json.dumps(meta,indent=2)+'\n')
        # All downloads and dependency checks finish before replacing either working-tree package.
        for group in ROOTS:
            shutil.rmtree(DEST/group)
            shutil.copytree(staged/group,DEST/group)
        index();verify()
    print('Working tree updated. Review diff, licenses, XSD tests and CI before merging; no release was triggered.')
if __name__=='__main__': main()
