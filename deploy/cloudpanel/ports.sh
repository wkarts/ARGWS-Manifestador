#!/usr/bin/env bash
set -euo pipefail
APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
set -a
[[ -f "$APP_DIR/.env" ]] && source "$APP_DIR/.env"
set +a

RESPECT_CLOUDPANEL_PORT="${MANIFESTADOR_NFE_RESPECT_CLOUDPANEL_PORT:-true}"
WEB_PORT="${MANIFESTADOR_NFE_WEB_PORT:-61002}"
if [[ "$RESPECT_CLOUDPANEL_PORT" =~ ^(1|true|TRUE|yes|YES|sim|SIM|on|ON)$ ]] && [[ -n "${PORT:-}" ]]; then
  WEB_PORT="$PORT"
fi

cat <<PORTS
Portas configuradas:

API Headless:
  Host: ${MANIFESTADOR_NFE_API_HOST:-127.0.0.1}
  Porta: ${MANIFESTADOR_NFE_API_PORT:-61001}
  URL: http://${MANIFESTADOR_NFE_API_HOST:-127.0.0.1}:${MANIFESTADOR_NFE_API_PORT:-61001}

Web / Browser / WebPort:
  Host: ${MANIFESTADOR_NFE_WEB_HOST:-127.0.0.1}
  Porta: $WEB_PORT
  URL: http://${MANIFESTADOR_NFE_WEB_HOST:-127.0.0.1}:$WEB_PORT

Webhook:
  Habilitado: ${MANIFESTADOR_NFE_WEBHOOK_ENABLED:-false}
  Host: ${MANIFESTADOR_NFE_WEBHOOK_HOST:-127.0.0.1}
  Porta: ${MANIFESTADOR_NFE_WEBHOOK_PORT:-61003}
  URL: http://${MANIFESTADOR_NFE_WEBHOOK_HOST:-127.0.0.1}:${MANIFESTADOR_NFE_WEBHOOK_PORT:-61003}${MANIFESTADOR_NFE_WEBHOOK_BASE_PATH:-/webhooks}

WebSocket:
  Habilitado: ${MANIFESTADOR_NFE_WEBSOCKET_ENABLED:-false}
  Host: ${MANIFESTADOR_NFE_WEBSOCKET_HOST:-127.0.0.1}
  Porta: ${MANIFESTADOR_NFE_WEBSOCKET_PORT:-61004}
  URL: ws://${MANIFESTADOR_NFE_WEBSOCKET_HOST:-127.0.0.1}:${MANIFESTADOR_NFE_WEBSOCKET_PORT:-61004}${MANIFESTADOR_NFE_WEBSOCKET_PATH:-/ws}

Publicar todas as portas: ${MANIFESTADOR_NFE_PUBLISH_ALL_PORTS:-false}
Iniciar todas as portas: ${MANIFESTADOR_NFE_START_ALL_PORTS:-false}
Respeitar PORT do CloudPanel: ${MANIFESTADOR_NFE_RESPECT_CLOUDPANEL_PORT:-true}
PORTS
