#!/usr/bin/env bash
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PID_FILE="$APP_DIR/manifestador-nfe.pid"
LOG_DIR="$APP_DIR/logs"
LOG_FILE="$LOG_DIR/manifestador-nfe.log"
ENV_FILE="$APP_DIR/.env"

mkdir -p "$LOG_DIR" "$APP_DIR/data"

set -a
[[ -f "$ENV_FILE" ]] && source "$ENV_FILE"
set +a

bool_true() {
  case "${1:-}" in
    1|true|TRUE|yes|YES|sim|SIM|on|ON) return 0 ;;
    *) return 1 ;;
  esac
}

BIN_PATH="${MANIFESTADOR_NFE_BINARY:-$APP_DIR/bin/manifestador_nfe}"
if [[ "$BIN_PATH" != /* ]]; then
  BIN_PATH="$APP_DIR/${BIN_PATH#./}"
fi

if [[ -f "$PID_FILE" ]] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
  echo "Manifestador NF-e já está em execução. PID: $(cat "$PID_FILE")"
  exit 0
fi

if [[ ! -x "$BIN_PATH" ]]; then
  echo "Binário não encontrado ou sem permissão de execução: $BIN_PATH"
  echo "Execute: chmod +x $APP_DIR/bin/manifestador_nfe"
  exit 1
fi

PUBLISH_ALL_PORTS="${MANIFESTADOR_NFE_PUBLISH_ALL_PORTS:-false}"
START_ALL_PORTS="${MANIFESTADOR_NFE_START_ALL_PORTS:-false}"
RESPECT_CLOUDPANEL_PORT="${MANIFESTADOR_NFE_RESPECT_CLOUDPANEL_PORT:-true}"
PUBLIC_BIND_HOST="${MANIFESTADOR_NFE_PUBLIC_BIND_HOST:-0.0.0.0}"

if bool_true "$PUBLISH_ALL_PORTS"; then
  export MANIFESTADOR_NFE_API_HOST="${MANIFESTADOR_NFE_API_HOST:-$PUBLIC_BIND_HOST}"
  export MANIFESTADOR_NFE_WEB_HOST="${MANIFESTADOR_NFE_WEB_HOST:-$PUBLIC_BIND_HOST}"
  export MANIFESTADOR_NFE_WEBHOOK_HOST="${MANIFESTADOR_NFE_WEBHOOK_HOST:-$PUBLIC_BIND_HOST}"
  export MANIFESTADOR_NFE_WEBSOCKET_HOST="${MANIFESTADOR_NFE_WEBSOCKET_HOST:-$PUBLIC_BIND_HOST}"
  export MANIFESTADOR_NFE_API_ALLOW_PUBLIC_NETWORK="${MANIFESTADOR_NFE_API_ALLOW_PUBLIC_NETWORK:-true}"
  export MANIFESTADOR_NFE_API_CORS="${MANIFESTADOR_NFE_API_CORS:-true}"
  export MANIFESTADOR_NFE_WEB_BIND_LAN="${MANIFESTADOR_NFE_WEB_BIND_LAN:-true}"
  export MANIFESTADOR_NFE_WEBHOOK_ALLOW_LAN="${MANIFESTADOR_NFE_WEBHOOK_ALLOW_LAN:-true}"
  export MANIFESTADOR_NFE_WEBHOOK_ALLOW_EXTERNAL="${MANIFESTADOR_NFE_WEBHOOK_ALLOW_EXTERNAL:-true}"
  export MANIFESTADOR_NFE_WEBSOCKET_ALLOW_LAN="${MANIFESTADOR_NFE_WEBSOCKET_ALLOW_LAN:-true}"
  export MANIFESTADOR_NFE_WEBSOCKET_ALLOW_EXTERNAL="${MANIFESTADOR_NFE_WEBSOCKET_ALLOW_EXTERNAL:-true}"
fi

if bool_true "$START_ALL_PORTS"; then
  export MANIFESTADOR_NFE_WEBHOOK_ENABLED=true
  export MANIFESTADOR_NFE_WEBHOOK_AUTO_START=true
  export MANIFESTADOR_NFE_WEBSOCKET_ENABLED=true
  export MANIFESTADOR_NFE_WEBSOCKET_AUTO_START=true
  export MANIFESTADOR_NFE_SERVICES_AUTO_START=true
fi

export MANIFESTADOR_NFE_ENV_FILE="${MANIFESTADOR_NFE_ENV_FILE:-$ENV_FILE}"
export MANIFESTADOR_NFE_WEB_DIST_DIR="${MANIFESTADOR_NFE_WEB_DIST_DIR:-$APP_DIR/dist}"
export MANIFESTADOR_NFE_DATA_DIR="${MANIFESTADOR_NFE_DATA_DIR:-$APP_DIR/data}"
export MANIFESTADOR_NFE_LOGS_DIR="${MANIFESTADOR_NFE_LOGS_DIR:-$LOG_DIR}"
export MANIFESTADOR_NFE_API_HOST="${MANIFESTADOR_NFE_API_HOST:-127.0.0.1}"
export MANIFESTADOR_NFE_API_PORT="${MANIFESTADOR_NFE_API_PORT:-61001}"
export MANIFESTADOR_NFE_WEB_HOST="${MANIFESTADOR_NFE_WEB_HOST:-127.0.0.1}"

if bool_true "$RESPECT_CLOUDPANEL_PORT" && [[ -n "${PORT:-}" ]]; then
  export MANIFESTADOR_NFE_WEB_PORT="$PORT"
else
  export MANIFESTADOR_NFE_WEB_PORT="${MANIFESTADOR_NFE_WEB_PORT:-61002}"
fi

export MANIFESTADOR_NFE_WEB_ENABLED="${MANIFESTADOR_NFE_WEB_ENABLED:-true}"
export MANIFESTADOR_NFE_WEB_AUTO_START="${MANIFESTADOR_NFE_WEB_AUTO_START:-true}"
export MANIFESTADOR_NFE_SERVICES_AUTO_START="${MANIFESTADOR_NFE_SERVICES_AUTO_START:-true}"
export MANIFESTADOR_NFE_WEBHOOK_HOST="${MANIFESTADOR_NFE_WEBHOOK_HOST:-127.0.0.1}"
export MANIFESTADOR_NFE_WEBHOOK_PORT="${MANIFESTADOR_NFE_WEBHOOK_PORT:-61003}"
export MANIFESTADOR_NFE_WEBSOCKET_HOST="${MANIFESTADOR_NFE_WEBSOCKET_HOST:-127.0.0.1}"
export MANIFESTADOR_NFE_WEBSOCKET_PORT="${MANIFESTADOR_NFE_WEBSOCKET_PORT:-61004}"

ARGS=(
  --mode=headless-api
  --host "$MANIFESTADOR_NFE_API_HOST"
  --port "$MANIFESTADOR_NFE_API_PORT"
  --data-dir "$MANIFESTADOR_NFE_DATA_DIR"
  --start-web-proxy
  --start-services
)

if [[ "${MANIFESTADOR_NFE_WEBHOOK_ENABLED:-false}" == "true" ]]; then
  ARGS+=(--start-webhook)
fi

if [[ "${MANIFESTADOR_NFE_WEBSOCKET_ENABLED:-false}" == "true" ]]; then
  ARGS+=(--start-websocket)
fi

cd "$APP_DIR"
nohup "$BIN_PATH" "${ARGS[@]}" >> "$LOG_FILE" 2>&1 &

echo $! > "$PID_FILE"
echo "Manifestador NF-e iniciado. PID: $(cat "$PID_FILE")"
echo "WebPort:  http://$MANIFESTADOR_NFE_WEB_HOST:$MANIFESTADOR_NFE_WEB_PORT"
echo "API:      http://$MANIFESTADOR_NFE_API_HOST:$MANIFESTADOR_NFE_API_PORT"
echo "Webhook:  http://$MANIFESTADOR_NFE_WEBHOOK_HOST:$MANIFESTADOR_NFE_WEBHOOK_PORT${MANIFESTADOR_NFE_WEBHOOK_BASE_PATH:-/webhooks} (${MANIFESTADOR_NFE_WEBHOOK_ENABLED:-false})"
echo "WebSocket: ws://$MANIFESTADOR_NFE_WEBSOCKET_HOST:$MANIFESTADOR_NFE_WEBSOCKET_PORT${MANIFESTADOR_NFE_WEBSOCKET_PATH:-/ws} (${MANIFESTADOR_NFE_WEBSOCKET_ENABLED:-false})"
echo "Logs:     $LOG_FILE"
